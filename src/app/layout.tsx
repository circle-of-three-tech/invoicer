import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono, Space_Grotesk } from "next/font/google";
import "./globals.css";
import { Backdrop } from "@/components/Backdrop";

// `display: "swap"` keeps text visible while the webfont loads, and preloading
// only the display face avoids three blocking font requests on first paint.
const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
  display: "swap",
});
const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
  display: "swap",
  preload: false,
});
const display = Space_Grotesk({
  variable: "--font-display",
  subsets: ["latin"],
  weight: ["500", "600", "700"],
  display: "swap",
});

export const metadata: Metadata = {
  title: {
    default: "Circle of Three — Invoicing & Receipts",
    template: "%s · Circle of Three",
  },
  description:
    "Create stylish invoices and matching receipts in seconds. By Circle of Three Technologies.",
  applicationName: "Circle of Three Invoicing",
  // Private billing data: keep the whole app out of search indexes.
  robots: { index: false, follow: false, nocache: true },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: "#ffffff",
};

export default function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} ${display.variable} h-full antialiased`}
    >
      <body className="min-h-full">
        <Backdrop />
        {children}
      </body>
    </html>
  );
}
